/** Turns a line into a matcher for bodies made from it, so recently used lines can be recognised after filling. */
export function lineMatcher(line: string): RegExp {
  const parts = line.split(/(\{TOKEN\}|\{SYM\}|\{USER\})/);
  const src = parts.map((p) => (p === '{TOKEN}' ? '[1-9A-HJ-NP-Za-km-z]{32,44}' : p === '{SYM}' ? '\\$[A-Za-z0-9]+' : p === '{USER}' ? '@\\w+' : p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))).join('');
  return new RegExp(`^${src}(?:\\n\\nCA: \\S+)?$`);
}

/**
 * Picks a line not used by any of `recentBodies`. Falls back to the least recently used line when every
 * line has been used recently, so it never repeats while a fresh line exists.
 */
export function pickFresh(r: () => number, lines: readonly string[], recentBodies: readonly string[]): string {
  const lastUse = (l: string) => { const m = lineMatcher(l); for (let i = recentBodies.length - 1; i >= 0; i--) if (m.test(recentBodies[i]!)) return i; return -1; };
  const uses = lines.map((l) => [l, lastUse(l)] as const);
  const fresh = uses.filter(([, i]) => i < 0).map(([l]) => l);
  if (fresh.length) return fresh[Math.floor(r() * fresh.length)]!;
  return uses.reduce((a, b) => (b[1] < a[1] ? b : a))[0];
}

/**
 * Draws lines without repeating any of the last `window` draws (capped below the number of distinct lines).
 * A line listed twice is twice as likely. Deterministic for a given rng.
 */
export function lineDrawer(r: () => number, lines: readonly string[], window: number) {
  const recent: string[] = [];
  const w = Math.min(window, new Set(lines).size - 1);
  return () => {
    const fresh = lines.filter((l) => !recent.includes(l));
    const line = fresh[Math.floor(r() * fresh.length)]!;
    recent.push(line);
    if (recent.length > w) recent.shift();
    return line;
  };
}

